#!/usr/bin/env node
'use strict';
/** Regenerate reference/vocabulary-bank.md and reference/exclusion-presets.md from lib/grammar.js and lib/lanes.js. */
const fs = require('fs');
const path = require('path');
const G = require('../lib/grammar');
const { LANES } = require('../lib/lanes');
const root = path.join(__dirname, '..');
const bullets = (arr) => arr.map((x) => `- ${x}`).join('\n');
const fam = (name, f) => `**${name}** (${f.frame})\n\nSources (description | handle):\n${bullets(f.sources.map((s) => s.replace('|', ' | ')))}\n\nProcessing characters:\n${bullets(f.character)}\n`;
let md = `# Vocabulary bank

Generated from \`lib/grammar.js\` and \`lib/lanes.js\` by \`node scripts/docs.js\` (edit those files, not this one). Every phrase passes the guard; see \`reference/grammar-and-guard.md\` for the rules and why labels are banned. The records behind each lane are named only in README and research, never here or in prompts.

## Shared slots (every lane)

**Lead register** (low or low-mid; high leads come back shrill)\n${bullets(G.LEAD.register)}\n
**Lead articulation**\n${bullets(G.LEAD.articulation)}\n
**Lead motif**\n${bullets(G.LEAD.motif)}\n
**Human timing (the anti-quantize slot)**\n${bullets(G.LEAD.human)}\n
**Motion across the song**\n${bullets(G.LEAD.motion)}\n
**Placement**\n${bullets(G.LEAD.placement)}\n
**Bass tone**\n${bullets(G.BASS.tone)}\n
**Bass pattern (base)**\n${bullets(G.BASS.pattern)}\n
**Bass human**\n${bullets(G.BASS.human)}\n
**Twitch percussion: sound / rhythm / where**\n${bullets(G.TWITCH.sound)}\n\n${bullets(G.TWITCH.rhythm)}\n\n${bullets(G.TWITCH.where)}\n
**Groove: syncopation**\n${bullets(G.GROOVE.sync)}\n
**Groove: human feel**\n${bullets(G.GROOVE.human)}\n
**Groove: the beat-3 slur (never "waltz", "shuffle" or "swing")**\n${bullets(G.GROOVE.triplet)}\n
**Head tags: syncopation / twitch / slur / low lead / loop / straight**\n${bullets(G.RHYTHM.sync)}\n\n${bullets(G.RHYTHM.twitch)}\n\n${bullets(G.RHYTHM.slur)}\n\n${bullets(G.RHYTHM.low)}\n\n${bullets(G.RHYTHM.loop)}\n\n${bullets(G.RHYTHM.straight)}\n
**Anti-transition phrases (one in every drums line)**\n${bullets(G.ANTI_TRANSITION)}\n
**Beat-switch axes (tag / cue / after-words)**\n${bullets(G.SWITCH.axes.map((a) => `${a.tag} / ${a.cue} / ${a.after}`))}\n\nLandings:\n${bullets(G.SWITCH.land)}\n
**Percussion colour (base)**\n${bullets(G.COLOR)}\n
**Counter roles**\n${bullets(G.COUNTER_ROLE)}\n
## Guest families (experimental palette any lane may borrow for the lead)

${Object.entries(G.FAMILIES).map(([n, f]) => fam(n, f)).join('\n')}
`;
for (const [id, l] of Object.entries(LANES)) {
  md += `\n## Lane \`${id}\`: ${l.label}\n\n${l.blurb}\n\n**Anchors** (sound-neutral when the lead is a guest: "${l.neutralAnchor}")\n${bullets(l.anchors)}\n\n**Mix tag:** ${l.mixTag} (neutral: ${l.neutralMixTag})\n\n**Tempo:** ${l.tempo.map((t) => t.join('-')).filter((x, i, a) => a.indexOf(x) === i).join(' or ')} BPM (half-time above ${l.halfTimeAbove}). Major share ${l.majorShare}, soul/Dorian loops ${l.soulShare}, slur tag ${l.slurShare}, low lead ${l.lowShare}. Modes ${l.modes.map(([m, w]) => `${m} ${w}`).join(', ')}. Sliders Weirdness ${l.sliders.weirdness.join('-')}, Style Influence ${l.sliders.styleInfluence.join('-')}.\n\n`;
  md += `**Families** (weights ${Object.entries(l.families).map(([f, w]) => `${f} ${w}`).join(', ')}; guest share ${l.guestShare})\n\n${Object.entries(l.FAMILIES).map(([n, f]) => fam(n, f)).join('\n')}\n`;
  md += `**Bass**\n${bullets(l.bass)}\n\nBass patterns:\n${bullets(l.bassPattern)}\n\n**Kick**\n${bullets(l.drums.kick)}\n\n**Snare**\n${bullets(l.drums.snare)}\n\n**Hats**\n${bullets(l.drums.hats)}\n\n${l.color ? `**Percussion colour**\n${bullets(l.color)}\n\n` : ''}**Exclude Styles:** ${l.exclude.join(', ')}\n\n**Guard:** allow ${l.allow ? l.allow.source : 'none'}; deny ${l.deny.re.source} (${l.deny.why}).\n`;
}
fs.writeFileSync(path.join(root, 'reference/vocabulary-bank.md'), md);
const ex = `# Exclude Styles presets

Rules: bare nouns, comma-separated, never negated ("vocals", not "no vocals"); the field is a bias, not a ban. Never exclude something the Style field asks for. Every lane list starts with the vocal guards and carries the transition guards (fills, rolls, risers, transitions), because section changes grow fills unless they are banned three ways (vocabulary, positive instruction, Exclude). Limit 1,000 characters. Lists live in \`lib/lanes.js\`; this file is generated by \`node scripts/docs.js\`.

## Per-lane defaults

| Lane | Exclude Styles |
|---|---|
${Object.entries(LANES).map(([id, l]) => `| \`${id}\` | ${l.exclude.join(', ')} |`).join('\n')}

The phonk lane says "lead vocals, singing, rapping" instead of "vocals, vocal chops" so its sample-stab textures survive; "cowbell melody" is excluded there because the cowbell is a knock, never the lead.

## Situational add-ons (\`--exclude "..."\` or the page's Extra Exclude field)

| Problem heard | Add |
|---|---|
| Wordless "ooh" pads or sustained vowels | wordless vocals, choir, vocal pad |
| Spoken intro / DJ drop | spoken intro, DJ tags, crowd noise |
| Sung hook on a bouncy beat | pop vocals, autotune, chorus vocals |
| Beat turns into an EDM drop | EDM drops, supersaw, sidechain pump, big room |
| Beat turns into a trailer cue | cinematic trailer, epic orchestra, braams |
| Fills or rolls at every section change | drum fills, tom fills, hat rolls, crash cymbals, reverse cymbals, impacts |
| Phonk slides into drift phonk | drift phonk, cowbell melody, Brazilian funk, gym music |
| Rigid drum machine on the live lane | quantized drums, drum machine, trap hi-hats |
| Too clean for lo-fi lanes | clean pop mix, polished pop production |
| Guitar appears uninvited | acoustic guitar, electric guitar solo |
| Piano ballad drift | piano ballad, solo piano, slow ballad |
`;
fs.writeFileSync(path.join(root, 'reference/exclusion-presets.md'), ex);
console.log('wrote reference/vocabulary-bank.md and reference/exclusion-presets.md');
