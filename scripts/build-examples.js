#!/usr/bin/env node
'use strict';
/** Regenerate examples/*.md deterministically and fail if any block does not pass QA. */
const fs = require('fs');
const path = require('path');
const { generate, LANES } = require('../lib/generate');
const { renderBlock } = require('../lib/render');
const { checkBlock } = require('../lib/qa');

const EXAMPLES = {
  'connor-price': { lane: 'connor-price', bpm: 140, key: 'B minor', mood: 'playful, sunny', arc: 'stop-start', seed: 2026 },
  'paak-pocket': { lane: 'paak-pocket', bpm: 94, key: 'D Dorian', mood: 'sun-soaked, late-night', arc: 'build-release', seed: 2026 },
  'jid-dark': { lane: 'jid-dark', bpm: 146, key: 'E minor', mood: 'paranoid, relentless', arc: 'beat-switch', seed: 2026 },
  'phonk-experimental': { lane: 'phonk-experimental', bpm: 138, key: 'G minor', mood: 'haunted, woozy', arc: 'stop-start', seed: 2026 },
  'hybrid': JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'examples', 'config.hybrid.json'), 'utf8')),
};

let failed = 0;
for (const [name, input] of Object.entries(EXAMPLES)) {
  if (!LANES[input.lane]) throw new Error(`unknown lane ${input.lane}`);
  const block = generate(input);
  const qa = checkBlock(block);
  const header = `<!-- Generated by scripts/build-examples.js with input ${JSON.stringify(input)}. QA: ${qa.ok ? 'PASS' : 'FAIL'}. Regenerate with: node forge.js ${Object.entries(input).map(([k, v]) => `--${k} ${JSON.stringify(String(v))}`).join(' ')} -->\n\n`;
  const out = path.join(__dirname, '..', 'examples', `${name}.md`);
  fs.writeFileSync(out, header + renderBlock(block) + '\n');
  console.log(`${qa.ok ? 'PASS' : 'FAIL'} examples/${name}.md  style ${qa.stats.styleChars} | lyrics ${qa.stats.lyricsChars} | exclude ${qa.stats.excludeChars} | ${block.plan.totalFormatted}, hook ${block.plan.hookAt}`);
  for (const e of qa.errors) console.log(`   ERROR ${e}`);
  for (const w of qa.warnings) console.log(`   warn  ${w}`);
  if (!qa.ok) failed++;
}
process.exitCode = failed ? 1 : 0;
