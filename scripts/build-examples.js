#!/usr/bin/env node
'use strict';
/** Regenerate examples/*.md deterministically and fail if any block does not pass QA. */
const fs = require('fs');
const path = require('path');
const { generate, LANES } = require('../lib/engine');
const { renderBlock } = require('../lib/render');
const { checkBlock } = require('../lib/qa');

const EXAMPLES = {
  'connor-price': { lane: 'connor-price', bpm: 140, mood: 'sunny', seed: 2026 },
  'paak-pocket': { lane: 'paak-pocket', bpm: 94, key: 'D dorian', mood: 'sun-soaked, late-night', seed: 2026 },
  'jid-dark': { lane: 'jid-dark', bpm: 146, mode: 'switch', mood: 'paranoid', seed: 2026 },
  'phonk-experimental': { lane: 'phonk-experimental', bpm: 138, mode: 'loop', mood: 'dark', seed: 2026 },
  'hybrid': JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'examples', 'config.hybrid.json'), 'utf8')),
};

let failed = 0;
for (const [name, input] of Object.entries(EXAMPLES)) {
  if (!LANES[input.lane]) throw new Error(`unknown lane ${input.lane}`);
  const block = generate(input);
  const qa = checkBlock(block);
  const flags = Object.entries(input).map(([k, v]) => `--${k} ${JSON.stringify(String(v))}`).join(' ');
  const header = `<!-- Generated by scripts/build-examples.js. QA: ${qa.ok ? 'PASS' : 'FAIL'}. Regenerate with: node forge.js ${flags} -->\n\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'examples', `${name}.md`), header + renderBlock(block) + '\n');
  console.log(`${qa.ok ? 'PASS' : 'FAIL'} examples/${name}.md  style ${qa.stats.styleChars} | lyrics ${qa.stats.lyricsChars} | exclude ${qa.stats.excludeChars} | ${block.meta.layout} | about ${block.plan.totalFormatted}, full beat ${block.plan.hookAt}`);
  for (const e of qa.errors) console.log(`   ERROR ${e}`);
  for (const w of [...qa.warnings, ...block.warnings]) console.log(`   warn  ${w}`);
  if (!qa.ok) failed++;
}
process.exitCode = failed ? 1 : 0;
