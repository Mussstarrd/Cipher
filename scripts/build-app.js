#!/usr/bin/env node
'use strict';
/**
 * Bundle lib/ into a single self-contained HTML page (app/index.html) with a Generate button
 * and Copy buttons. No build tools: the CommonJS modules are wrapped in a tiny require shim and
 * the JSON data is inlined. Open the result by double-clicking, or publish it as a page.
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const modules = { './arrange': 'lib/arrange.js', './guard': 'lib/guard.js', './theory': 'lib/theory.js', './grammar': 'lib/grammar.js', './lanes': 'lib/lanes.js', './layouts': 'lib/layouts.js', './engine': 'lib/engine.js', './qa': 'lib/qa.js', './render': 'lib/render.js' };
const json = { 'spec.json': read('lib/spec.json') };

let bundle = `// suno-forge browser bundle (generated by scripts/build-app.js; do not edit by hand)
(function () {
  const __json = ${JSON.stringify(json)};
  const __defs = {}, __cache = {};
  const __fs = { readFileSync: (p) => { const k = String(p).split('/').pop(); if (!(k in __json)) throw new Error('no file ' + p); return __json[k]; } };
  const __path = { join: (...a) => a.join('/') };
  function __require(name) {
    if (name === 'fs') return __fs;
    if (name === 'path') return __path;
    const key = name.replace(/\\.js$/, '');
    if (__cache[key]) return __cache[key].exports;
    if (!__defs[key]) throw new Error('module not bundled: ' + name);
    const module = { exports: {} }; __cache[key] = module;
    __defs[key](module, module.exports, __require, '');
    return module.exports;
  }
`;
for (const [key, file] of Object.entries(modules)) {
  bundle += `  __defs[${JSON.stringify(key)}] = function (module, exports, require, __dirname) {\n${read(file)}\n  };\n`;
}
bundle += `  window.SunoForge = { ...__require('./engine'), ...__require('./qa'), ...__require('./render'), guard: __require('./guard'), layouts: __require('./layouts') };
})();`;

const template = read('app/src/index.template.html');
const stamp = new Date().toISOString().slice(0, 10);
const spec = JSON.parse(json['spec.json']);
const html = template
  .replace('/*__BUNDLE__*/', () => bundle)
  .replace(/__BUILD_DATE__/g, stamp)
  .replace(/__SPEC_VERIFIED__/g, spec.verifiedOn)
  .replace(/__MODELS__/g, spec.models.list.join(' / '));
fs.writeFileSync(path.join(root, 'app', 'index.html'), html);
console.log(`wrote app/index.html (${(html.length / 1024).toFixed(0)} KB)`);
